#!/usr/bin/env bash
# Famboook Next.js — isolated release build (FB-DEVOPS-01).
# Runbook: docs/deployment/FB-DEVOPS-01-ISOLATED-FRONTEND-BUILDS.md
#
#   deploy/scripts/build-frontend.sh <release-id>
#
# Builds frontend/.builds/<release-id> while the active release keeps serving.
# It never installs dependencies (node_modules is shared: see the runbook),
# never deletes or overwrites a release, never activates one, and never reverts
# a file. Run it as the deploy user, from any directory.
set -euo pipefail

die() { printf 'build-frontend: %s\n' "$*" >&2; exit 1; }

[[ $# -eq 1 ]] || die "usage: build-frontend.sh <release-id>"
RELEASE_ID=$1
# The same rule as frontend/lib/release-dir.ts.
[[ $RELEASE_ID =~ ^[a-z0-9][a-z0-9-]{0,39}$ ]] \
  || die "invalid release id '$RELEASE_ID': use lowercase letters, digits and '-', 1-40 characters, starting with a letter or digit"
[[ $(id -u) -ne 0 ]] || die "refusing to run as root: build as the deploy user so the release stays writable by it"

for tool in git node flock; do
  command -v "$tool" >/dev/null 2>&1 || die "required tool not found: $tool"
done

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
REPO=$(cd "$SCRIPT_DIR/../.." && pwd)
FRONTEND=$REPO/frontend
[[ -f $FRONTEND/package.json && -f $FRONTEND/next.config.ts && -f $FRONTEND/tsconfig.json ]] \
  || die "the frontend was not found at $FRONTEND"
git -C "$REPO" rev-parse --verify --quiet HEAD >/dev/null || die "$REPO is not a Git checkout with a commit"
NEXT_CLI=$FRONTEND/node_modules/next/dist/bin/next
[[ -f $NEXT_CLI ]] || die "Next.js is not installed in $FRONTEND/node_modules: install dependencies first (runbook, 'Dependencies')"

# A production build reads these files; one of them or the environment must set the API URL.
if [[ -z ${NEXT_PUBLIC_API_URL:-} ]] \
  && ! grep -qs '^NEXT_PUBLIC_API_URL=.' "$FRONTEND/.env.production.local" "$FRONTEND/.env.local" "$FRONTEND/.env.production" "$FRONTEND/.env"; then
  die "NEXT_PUBLIC_API_URL is not set in the environment or in frontend/.env.production(.local)"
fi

BUILDS=$FRONTEND/.builds
RELEASE_DIR=$BUILDS/$RELEASE_ID
RELEASE_TSCONFIG=$BUILDS/$RELEASE_ID.tsconfig.json
METADATA=$RELEASE_DIR/famboook-release.json
NEXT_ENV=$FRONTEND/next-env.d.ts
NEXT_ENV_BACKUP=$BUILDS/.next-env.d.ts.before-$RELEASE_ID

mkdir -p "$BUILDS"
exec 9>"$BUILDS/.build.lock"
flock -n 9 || die "another build holds $BUILDS/.build.lock: wait for it to finish"

# Checked under the lock. mkdir without -p reserves the name.
[[ ! -e $RELEASE_DIR && ! -e $RELEASE_TSCONFIG ]] \
  || die "release '$RELEASE_ID' already exists: choose a new release id (releases are never overwritten)"
mkdir "$RELEASE_DIR"

# Tracked files that differ from HEAD, with their content hash. Compared before
# and after the build: changes made earlier stay as they are, and only a change
# made during the build fails it.
tracked_state() {
  local path
  git -C "$REPO" diff --name-only -z HEAD -- | while IFS= read -r -d '' path; do
    if [[ -e $REPO/$path ]]; then
      printf '%s %s\n' "$(git -C "$REPO" hash-object -- "$path")" "$path"
    else
      printf 'deleted %s\n' "$path"
    fi
  done
}

# Next.js rewrites next-env.d.ts (ignored by Git) to import this release's types.
# Put the earlier state back afterwards, whatever happens.
restore_next_env() {
  if [[ -f $NEXT_ENV_BACKUP ]]; then
    cp -p "$NEXT_ENV_BACKUP" "$NEXT_ENV" && rm -f "$NEXT_ENV_BACKUP"
  else
    rm -f "$NEXT_ENV"
  fi
}
if [[ -f $NEXT_ENV ]]; then cp -p "$NEXT_ENV" "$NEXT_ENV_BACKUP"; fi
trap restore_next_env EXIT
trap 'exit 130' INT TERM HUP

# The release's TypeScript configuration: the project's tsconfig.json with its
# include list, minus generated types under .next/ and .builds/, plus this
# release's generated types only. TypeScript's own parser reads the base file.
(cd "$FRONTEND" && node - "$RELEASE_ID" <<'NODE'
const fs = require("node:fs");
const ts = require(require.resolve("typescript", { paths: [process.cwd()] }));
const releaseId = process.argv[2];
const read = ts.readConfigFile("tsconfig.json", ts.sys.readFile);
if (read.error) throw new Error(ts.flattenDiagnosticMessageText(read.error.messageText, "\n"));
const generated = (pattern) => /^(\.\/)?\.(next|builds)(\/|$)/.test(pattern);
const fromBuilds = (pattern) => `../${pattern.replace(/^\.\//, "")}`;
const config = {
  extends: "../tsconfig.json",
  include: [...(read.config.include ?? ["**/*.ts", "**/*.tsx"]).filter((p) => !generated(p)).map(fromBuilds), `./${releaseId}/types/**/*.ts`],
  exclude: (read.config.exclude ?? ["node_modules"]).map(fromBuilds),
};
const header = `// Generated by deploy/scripts/build-frontend.sh for release ${releaseId} (FB-DEVOPS-01). Do not edit.\n`;
fs.writeFileSync(`.builds/${releaseId}.tsconfig.json`, header + JSON.stringify(config, null, 2) + "\n", { flag: "wx" });
NODE
) || die "could not generate $RELEASE_TSCONFIG"

COMMIT=$(git -C "$REPO" rev-parse HEAD)
TREE=clean
git -C "$REPO" diff --quiet HEAD -- || TREE=modified
BEFORE=$(tracked_state)
STARTED=$(date -u +%Y-%m-%dT%H:%M:%SZ)

printf 'build-frontend: building release %s from %s (%s working tree)\n' "$RELEASE_ID" "$COMMIT" "$TREE"
set +e
(cd "$FRONTEND" && FAMBOOOK_NEXT_DIST_DIR=".builds/$RELEASE_ID" node "$NEXT_CLI" build 9>&-)
BUILD_STATUS=$?
set -e

AFTER=$(tracked_state)
REASON=""
if [[ $BUILD_STATUS -ne 0 ]]; then
  REASON="next build exited with status $BUILD_STATUS"
elif [[ $BEFORE != "$AFTER" ]]; then
  REASON="the build changed tracked files (left as they are, for inspection)"
elif [[ ! -s $RELEASE_DIR/BUILD_ID || ! -f $RELEASE_DIR/routes-manifest.json || ! -d $RELEASE_DIR/server ]]; then
  REASON="the build output is incomplete (BUILD_ID, routes-manifest.json or server/ is missing)"
fi

STATUS=succeeded
[[ -z $REASON ]] || STATUS=failed
(cd "$FRONTEND" && node - "$METADATA" "$RELEASE_ID" "$STATUS" "$REASON" "$COMMIT" "$TREE" "$STARTED" "$(id -un)" <<'NODE'
const fs = require("node:fs");
const [file, releaseId, status, reason, commit, tree, startedAt, builder] = process.argv.slice(2);
const buildIdFile = `.builds/${releaseId}/BUILD_ID`;
const metadata = {
  release_id: releaseId,
  status,
  ...(reason ? { reason } : {}),
  dist_dir: `.builds/${releaseId}`,
  git_commit: commit,
  git_working_tree: tree,
  build_started_at: startedAt,
  build_finished_at: new Date().toISOString().replace(/\.\d{3}Z$/, "Z"),
  build_id: fs.existsSync(buildIdFile) ? fs.readFileSync(buildIdFile, "utf8").trim() : null,
  node_version: process.version,
  next_version: require(require.resolve("next/package.json", { paths: [process.cwd()] })).version,
  builder,
};
fs.writeFileSync(file, JSON.stringify(metadata, null, 2) + "\n");
NODE
) || die "could not write $METADATA"

if [[ -n $REASON ]]; then
  if [[ $BEFORE != "$AFTER" ]]; then
    printf 'build-frontend: tracked files before the build:\n%s\nafter:\n%s\n' "${BEFORE:-(none)}" "${AFTER:-(none)}" >&2
  fi
  die "release '$RELEASE_ID' FAILED: $REASON. It is marked failed in $METADATA and cannot be activated; build again under a new release id."
fi

cat <<EOF
build-frontend: release '$RELEASE_ID' built: $RELEASE_DIR
  commit $COMMIT ($TREE working tree), BUILD_ID $(cat "$RELEASE_DIR/BUILD_ID")
Next steps (runbook): smoke-test it, then switch to it:
  bash deploy/scripts/smoke-frontend-release.sh $RELEASE_ID
  sudo bash deploy/scripts/switch-frontend-release.sh $RELEASE_ID
EOF
